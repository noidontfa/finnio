// GetIngressURL godoc
// @Summary      Get stream ingress URL
// @Description  Returns the ingress URL for a stream by key
// @Tags         streams
// @Produce      json
// @Param        key  path  string  true  "Stream key (UUID)"
// @Success      200  {object}  entity.IngressURLResponse
// @Failure      404  {object}  entity.ErrorResponse
// @Failure      500  {object}  entity.ErrorResponse
// @Router       /streams/{key}/ingress [get]
func (h *Handler) GetIngressURL(w http.ResponseWriter, r *http.Request) error {
	key := r.PathValue("key")
	if key == "" {
		return middleware.BadRequest("stream key is required")
	}

	stream, err := h.stream.GetByKey(r.Context(), key)
	if err != nil {
		return err
	}
	out, err := entity.StreamFromDB(stream)
	if err != nil {
		return err
	}
	return h.response(w, entity.IngressURLResponse{
		Key: out.Key,
		URL: entity.BuildIngressURL(h.cfg.IngressURL, out.Key),
	}, http.StatusOK)
}

// ServeABRHLS serves FFmpeg-generated ABR HLS (master.m3u8 + variant playlists/segments).
// @Summary      Serve ABR HLS
// @Description  Serves FFmpeg-generated ABR HLS (master.m3u8 + variant playlists/segments)
// @Tags         streams
// @Produce      video/mp2t
// @Produce      application/vnd.apple.mpegurl
// @Param        key  path  string  true  "Stream key (UUID)"
// @Success      200  {file}  video/mp2t
// @Success      200  {file}  application/vnd.apple.mpegurl
// @Failure      400  {object}  entity.ErrorResponse
// @Failure      404  {object}  entity.ErrorResponse
// @Failure      500  {object}  entity.ErrorResponse
// @Router       /hls/{key} [get]
func (h *Handler) ServeABRHLS(w http.ResponseWriter, r *http.Request) error {
	key := r.PathValue("key")
	if key == "" || strings.Contains(key, "..") || strings.Contains(key, "/") {
		return middleware.BadRequest("invalid stream key")
	}

	if _, err := h.stream.GetByKey(r.Context(), key); err != nil {
		return err
	}

	// chi wildcard: /hls/{key}/* → PathValue("*")
	rel := filepath.Clean("/" + r.PathValue("*"))
	rel = strings.TrimPrefix(rel, "/")
	if rel == "" || rel == "." || strings.HasPrefix(rel, "..") {
		return middleware.BadRequest("invalid playlist path")
	}

	root := filepath.Clean(h.cfg.HLSAbrDir)
	full := filepath.Join(root, key, rel)
	log.Println(full)
	if !strings.HasPrefix(full, filepath.Join(root, key)+string(filepath.Separator)) &&
		full != filepath.Join(root, key) {
		return middleware.BadRequest("invalid playlist path")
	}

	if _, err := os.Stat(full); err != nil {
		if os.IsNotExist(err) {
			w.Header().Set("Access-Control-Allow-Origin", "*")
			w.Header().Set("Cache-Control", "no-cache, no-store, must-revalidate")
			ext := strings.ToLower(filepath.Ext(full))
			// Deleted/expired media segments are normal for a live sliding window.
			if ext == ".ts" {
				return middleware.NotFound("segment no longer in live window")
			}
			w.Header().Set("Retry-After", "2")
			return middleware.ServiceUnavailable("ABR playlist not ready yet; retry shortly")
		}
		return err
	}

	ext := strings.ToLower(filepath.Ext(full))
	w.Header().Set("Access-Control-Allow-Origin", "*")
	switch ext {
	case ".m3u8":
		// Serve playlist bytes directly so ServeFile cannot answer 304 against a
		// stale ETag/Last-Modified — that stalls live players until a hard refresh.
		data, err := os.ReadFile(full)
		if err != nil {
			if os.IsNotExist(err) {
				w.Header().Set("Cache-Control", "no-cache, no-store, must-revalidate")
				w.Header().Set("Retry-After", "2")
				return middleware.ServiceUnavailable("ABR playlist not ready yet; retry shortly")
			}
			return err
		}
		w.Header().Set("Content-Type", "application/vnd.apple.mpegurl")
		w.Header().Set("Cache-Control", "no-cache, no-store, must-revalidate")
		w.Header().Set("Pragma", "no-cache")
		w.WriteHeader(http.StatusOK)
		_, _ = w.Write(data)
		return nil
	case ".ts":
		w.Header().Set("Content-Type", "video/mp2t")
		w.Header().Set("Cache-Control", "public, max-age=10")
	}
	http.ServeFile(w, r, full)
	return nil
}
