type streamStatusTransition func(context.Context, string) (db.Stream, error)

func (h *Handler) handleStreamStatusTransition(
	w http.ResponseWriter,
	r *http.Request,
	transition streamStatusTransition,
) error {
	key := r.PathValue("key")
	if key == "" {
		return middleware.BadRequest("stream key is required")
	}

	stream, err := transition(r.Context(), key)
	if err != nil {
		if errors.Is(err, store.ErrNotFound) {
			return err
		}
		return middleware.BadRequest(err.Error())
	}
	out, err := entity.StreamFromDB(stream)
	if err != nil {
		return err
	}
	return h.response(w, out, http.StatusOK)
}

