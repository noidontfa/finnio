// UpdateStream godoc
// @Summary      Update stream
// @Description  Updates stream name and/or status
// @Tags         streams
// @Accept       json
// @Produce      json
// @Param        id    path      int                        true  "Stream ID"
// @Param        body  body      entity.UpdateStreamRequest  true  "Stream payload"
// @Success      200   {object}  entity.Stream
