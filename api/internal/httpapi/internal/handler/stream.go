// CreateStream godoc
// @Summary      Create stream
// @Description  Creates a new stream. ID and key are generated by the server.
// @Tags         streams
// @Accept       json
// @Produce      json
// @Param        body  body      entity.CreateStreamRequest  true  "Stream payload"
// @Success      201   {object}  entity.StreamResponse
// @Failure      400   {object}  entity.ErrorResponse
// @Failure      409   {object}  entity.ErrorResponse
// @Failure      500   {object}  entity.ErrorResponse
// @Router       /streams [post]
func (h *Handler) CreateStream(w http.ResponseWriter, r *http.Request) error {
	body, ok := middleware.Body[entity.CreateStreamRequest](r)
	if !ok {
		return middleware.Internal("missing request body")
	}

	status, err := entity.ToDBStreamStatus(body.Status)
	if err != nil {
		return middleware.BadRequest(err.Error())
	}

	created, err := h.stream.Create(r.Context(), body.Name, status)
	if err != nil {
		if errors.Is(err, store.ErrConflict) {
			return err
		}
		return middleware.BadRequest(err.Error())
	}
	resp, err := entity.StreamResponseFromDB(created, h.cfg.IngressURL, h.cfg.PublicURL)
	if err != nil {
		return err
	}
	return h.response(w, resp, http.StatusCreated)
}

func (h *Handler) streamID(r *http.Request) (int32, error) {
	id, err := strconv.ParseInt(r.PathValue("id"), 10, 32)
	if err != nil {
		return 0, middleware.BadRequest("invalid stream id")
	}
	return int32(id), nil
}

// GetStream godoc
